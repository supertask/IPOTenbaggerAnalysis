def get(title: str) -> Optional[dict]:
    """グラフのタイトルから説明を引く。無ければ None"""
    return HELP.get((title or "").strip())


_BOLD = re.compile(r"\*\*(.+?)\*\*", re.S)


def _to_html(text: str) -> str:
    """**強調** を太字にする。テンプレート側は素通しにするので、
    先にHTMLとして危ない文字を潰しておく"""
    return _BOLD.sub(r"<strong>\1</strong>", html.escape(text))


def rows(title: str):
    """テンプレートで回しやすい形にする"""
    item = get(title)
    if not item:
        return []
    labels = (("what", "何を表すか"), ("how", "どう計算しているか"),
              ("guide", "いくつなら良いか"),
              ("watch", "どこを見るか"), ("trap", "気をつける点"),
              ("who", "重く見る投資家"))
    return [{"label": label, "text": _to_html(item[key])}
            for key, label in labels if item.get(key)]
